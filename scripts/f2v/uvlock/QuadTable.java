import net.minecraft.client.renderer.block.model.BlockFaceUV;
import net.minecraft.client.renderer.block.model.FaceBakery;
import net.minecraft.client.resources.model.BlockModelRotation;
import net.minecraft.core.BlockMath;
import net.minecraft.core.Direction;
import com.mojang.math.Transformation;

public class QuadTable {
    public static void main(String[] args) {
        Direction[] faces = {Direction.DOWN, Direction.UP, Direction.NORTH, Direction.SOUTH, Direction.WEST, Direction.EAST};
        System.out.println("// generated by QuadTable from the real 1.21.1 classes");
        System.out.println("// quadrant[tier][faceIdx]: tier = BlockModelRotation ordinal");
        for (BlockModelRotation rot : BlockModelRotation.values()) {
            Transformation t = rot.getRotation();
            StringBuilder plain = new StringBuilder();
            StringBuilder lock = new StringBuilder();
            for (Direction f : faces) {
                BlockFaceUV uv = new BlockFaceUV(new float[]{0, 0, 16, 16}, 0);
                BlockFaceUV out = FaceBakery.recomputeUVs(uv, f, t);
                plain.append(out.rotation).append(',');
                BlockFaceUV uvl = new BlockFaceUV(new float[]{0, 0, 16, 16}, 0);
                Transformation lt = BlockMath.getUVLockTransform(t, f);
                BlockFaceUV outl = FaceBakery.recomputeUVs(uvl, f, lt);
                lock.append(outl.rotation).append(',');
            }
            System.out.printf("%s plain=[%s] uvlock=[%s]%n", rot.name(), plain, lock);
        }
        // the uv ARRAYS too (they may differ from the default for the locked cases)
        System.out.println("// uv arrays for uvlock (tier,face -> raw uvs):");
        for (BlockModelRotation rot : BlockModelRotation.values()) {
            Transformation t = rot.getRotation();
            for (Direction f : faces) {
                BlockFaceUV uvl = new BlockFaceUV(new float[]{0, 0, 16, 16}, 0);
                Transformation lt = BlockMath.getUVLockTransform(t, f);
                BlockFaceUV outl = FaceBakery.recomputeUVs(uvl, f, lt);
                float[] o = outl.uvs;
                if (o != null && (Math.abs(o[0]) > 0.01 || Math.abs(o[1]) > 0.01
                        || Math.abs(o[2] - 16) > 0.01 || Math.abs(o[3] - 16) > 0.01)) {
                    System.out.printf("%s %s uv=[%.4f,%.4f,%.4f,%.4f] rot=%d%n",
                        rot.name(), f, o[0], o[1], o[2], o[3], outl.rotation);
                }
            }
        }
    }
}
