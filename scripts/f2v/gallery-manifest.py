#!/usr/bin/env python3
"""Truth-leg gallery page manifests -> the ours-leg visual-gallery.tsv.

Reads the gallery-<ns>-p<p>.tsv manifests the cimscene gallery command
emits on the REAL modded server (cell|x|y|z|state rows + skip rows), takes
EVERY distinct state string in sorted order, and writes one state per line
(the pack's GalleryPack auto-assigns CMDs 100000+i in that order — the
same deterministic order the plugin's replay resolves through).

Usage: gallery-manifest.py <scenes-dir> <ns> <out-tsv> [pages...]
  scenes-dir  dir holding gallery-<ns>-p<p>.tsv (e.g. srv-create/c-imagine/scenes)
  ns          namespace filter ("create")
  out-tsv     the visual-gallery.tsv to write
  pages       page numbers to include (default: all present)
"""
import pathlib
import sys


def main() -> int:
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    scenes = pathlib.Path(sys.argv[1])
    ns = sys.argv[2]
    out = pathlib.Path(sys.argv[3])
    if len(sys.argv) > 4:
        pages = [int(p) for p in sys.argv[4:]]
    else:
        pages = sorted(
            int(p.name.rsplit("-p", 1)[1].split(".")[0])
            for p in scenes.glob(f"gallery-{ns}-p*.tsv")
        )
    states = set()
    cells = 0
    skips = 0
    for p in pages:
        mf = scenes / f"gallery-{ns}-p{p}.tsv"
        if not mf.is_file():
            print(f"WARN: manifest missing: {mf}", file=sys.stderr)
            continue
        for line in mf.read_text().splitlines()[1:]:
            parts = line.split("\t")
            if len(parts) < 5:
                continue
            kind, state = parts[0], parts[4]
            if kind == "cell":
                cells += 1
                states.add(state)
            elif kind == "skip":
                skips += 1
                states.add(state)
    rows = sorted(states)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# generated by gallery-manifest.py from the truth-leg page manifests\n"
        + "".join(r + "\n" for r in rows)
    )
    print(f"gallery-manifest: ns={ns} pages={pages} cells={cells} skips={skips} "
          f"distinct_states={len(rows)} -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
