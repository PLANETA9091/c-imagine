#!/usr/bin/env python3
"""Truth-leg sound manifests -> the F2V visual-sounds.tsv mapping.

THE SOUND CHANNEL's pack-side half (DIAGNOSTIC-first): every modded
SoundEvent id the truth walk played (the gallery-sound-<ns>-p<p>.tsv
manifests) gets a deterministic vanilla stand-in the vanilla 26.3 client
can actually resolve and play. The mapping is PURE FUNCTION of the
manifests (sorted ids), so the pack and the plugin always agree.

Heuristic per modded id ``ns:path`` (documented, in order):
  1. exact-name   -> ``minecraft:<path>`` (mods frequently reuse vanilla
     sound paths; the replay validates the target against the live Paper
     SOUND_EVENT registry before sending, so a removed/renamed vanilla
     path degrades to the default at replay time, never to silence);
  2. category:<kw> -> a small keyword table over the path:
       music            -> minecraft:music.menu
       ui./button/click -> minecraft:ui.button.click
       entity.          -> minecraft:entity.pig.ambient
       block./item.     -> minecraft:block.wood.place
  3. default       -> minecraft:block.wood.place.

The plugin (CimPlugin.galleryPageSound) reads this file from
``c-imagine/f2v/visual-sounds.tsv`` and records the POST-rewrite id the
vanilla client receives into the page capture log — sound-diff.py joins
the two ordered streams.

Usage: gallery-sounds-mapping.py <scenes-dir> <out-tsv>
  scenes-dir  dir holding gallery-sound-<ns>-p<p>.tsv (seed-pack/scenes)
  out-tsv     the visual-sounds.tsv to write
"""
import pathlib
import sys

DEFAULT = "minecraft:block.wood.place"

# ORDER MATTERS (first match wins): the specific buckets ride BEFORE the
# generic prefixes, so "mechanical_press_activation" lands on the piston
# bucket, not the "press"-in-path generic. Every target validated against
# the real 26.3 sound registry (1991 events, all present).
CATEGORY_TABLE = [
    # Create kinetic machinery -> mechanical motion
    ("cog", "minecraft:block.piston.extend"),
    ("crank", "minecraft:block.piston.extend"),
    ("press", "minecraft:block.piston.extend"),
    ("saw", "minecraft:block.piston.extend"),
    ("mixing", "minecraft:block.piston.extend"),
    ("millstone", "minecraft:block.piston.extend"),
    ("crushing", "minecraft:block.piston.extend"),
    ("drill", "minecraft:block.piston.extend"),
    ("deployer", "minecraft:block.piston.extend"),
    # trains and whistles -> the minecart ride
    ("whistle", "minecraft:entity.minecart.riding"),
    ("train", "minecraft:entity.minecart.riding"),
    # bells -> the bell
    ("bell", "minecraft:block.bell.use"),
    # item transfer -> the pickup/drink family
    ("funnel", "minecraft:entity.item.pickup"),
    ("package", "minecraft:entity.item.pickup"),
    ("hatch", "minecraft:entity.item.pickup"),
    ("depot", "minecraft:entity.item.pickup"),
    ("spout", "minecraft:entity.generic.drink"),
    ("steam", "minecraft:entity.generic.extinguish_fire"),
    # UI confirm/deny
    ("confirm", "minecraft:ui.button.click"),
    ("deny", "minecraft:entity.villager.no"),
    # generic families (the original buckets, kept last)
    ("music", "minecraft:music.menu"),
    ("ui.", "minecraft:ui.button.click"),
    ("button", "minecraft:ui.button.click"),
    ("click", "minecraft:ui.button.click"),
    ("entity.", "minecraft:entity.pig.ambient"),
    ("block.", "minecraft:block.wood.place"),
    ("item.", "minecraft:block.wood.place"),
]


def resolve(ns: str, path: str) -> tuple[str, str]:
    """(target, heuristic) for one sound id."""
    if ns == "minecraft":
        # a vanilla-namespace row never reaches here (LADDER_NS is modded),
        # but the identity is the honest answer if it ever does
        return f"minecraft:{path}", "exact-name"
    for kw, target in CATEGORY_TABLE:
        if kw in path:
            return target, f"category:{kw.rstrip('.')}"
    return DEFAULT, "default"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    scenes = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])
    ids = set()
    for mf in sorted(scenes.glob("gallery-sound-*-p*.tsv")):
        for line in mf.read_text(encoding="utf-8").splitlines()[1:]:
            parts = line.split("\t")
            if len(parts) >= 5 and parts[0] in ("cell", "skip"):
                ids.add(parts[4])
    rows = []
    counts: dict[str, int] = {}
    for sid in sorted(ids):
        ns, _, path = sid.partition(":")
        target, heuristic = resolve(ns, path)
        counts[heuristic.split(":")[0]] = counts.get(heuristic.split(":")[0], 0) + 1
        rows.append(f"{sid}\t{target}\t{heuristic}\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# generated by gallery-sounds-mapping.py from the truth-leg sound"
        " manifests (deterministic; do not edit)\n"
        "# Format (TSV): modded_sound_id <TAB> target_vanilla_sound_id <TAB> heuristic\n"
        "# heuristic: exact-name | category:<kw> | default (see the script docstring)\n"
        + "".join(rows)
    )
    print(f"gallery-sounds-mapping: {len(rows)} sound ids -> {out} "
          f"({counts.get('exact-name', 0)} exact-name, "
          f"{counts.get('category', 0)} category, {counts.get('default', 0)} default)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
