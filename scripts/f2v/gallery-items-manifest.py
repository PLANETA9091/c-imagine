#!/usr/bin/env python3
"""Truth-leg ITEM gallery manifests -> the ours-leg visual-gallery-items.tsv.

Reads the gallery-item-<ns>-p<p>.tsv manifests the cimscene gallery item
command emits on the REAL modded server (cell|x|y|z|item|dyn|note), takes
EVERY distinct item id in sorted order, and writes one visual-items row per
item: <moddedId><TAB>paper<TAB><cmd> — the paper host plus an EXPLICIT CMD
float in the dedicated item-gallery space (300000+i, disjoint from the block
gallery's 100000+ space and the pinned hand-written rows), deterministic
across runs because the input is the sorted registry walk.

The CI pack step APPENDS these rows to visual-items.tsv before F2vPack
--build: F2vPack resolves each item's model graph from the mod jars and
emits the range_dispatch entries the 26.3 client renders through the paper
CMD carrier — the same item-model channel the M5.2 hotbar datum proved.

Usage: gallery-items-manifest.py <scenes-dir> <ns> <out-tsv>
  scenes-dir  dir holding gallery-item-<ns>-p<p>.tsv (the staged truth scenes)
  ns          namespace filter ("create")
  out-tsv     the visual-gallery-items.tsv to write
"""
import pathlib
import sys

CMD_BASE = 300_000.0


def main() -> int:
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    scenes = pathlib.Path(sys.argv[1])
    ns = sys.argv[2]
    out = pathlib.Path(sys.argv[3])
    items = set()
    for mf in sorted(scenes.glob(f"gallery-item-{ns}-p*.tsv")):
        for line in mf.read_text(encoding="utf-8").splitlines()[1:]:
            parts = line.split("\t")
            if len(parts) >= 5 and parts[0] == "cell":
                items.add(parts[4].strip())
    rows = sorted(items)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        f.write("# generated by gallery-items-manifest.py — truth item"
                " manifests, sorted ids, item-gallery CMD space\n")
        for i, item in enumerate(rows):
            f.write(f"{item}\tpaper\t{CMD_BASE + i:.1f}\n")
    print(f"gallery-items-manifest: {len(rows)} items -> {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
